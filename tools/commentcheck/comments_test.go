package main

import (
	"go/parser"
	"go/token"
	"slices"
	"testing"
)

const source = `// Package sample is documented.
package sample

// Exported is documented.
type Exported struct {
	// Name is documented.
	Name string
	// hidden explains itself.
	hidden string
}

// helper narrates its body.
func helper() {
	// then it does something
	// Output: smuggled

	//go:noinline

	// Local narrates a local variable.
	var Local = 1
	_ = Local
}

	//go:generate go run golang.org/x/tools/cmd/stringer@v0.38.0 -type Exported -output sample_string.go

//go:narrate this is prose

//go:noinline this is prose too
func inlined() {}

// Documented carries a directive smuggled in its doc.
//go:noinline this is prose in a doc
func Documented() {}

func ExampleExported() {
	// Output: early
	helper()
	// Output: ok
}

func (Exported) ExampleMethod() {
	// Output: not an example
}

func Examplenarrative() {
	// Output: not an example either
}

type tree struct {
	// Name narrates a field of an unexported type.
	Name string
}

// Describe narrates a method of an unexported type.
func (*tree) Describe() {}

// Public is documented.
type Public struct {
	// Exported is documented, as an embedded exported type.
	Exported
	inner struct {
		// Name narrates a field nobody outside can reach.
		Name string
	}
}
`

const generated = `// Code generated by stringer. DO NOT EDIT.

package sample

// helper narrates its body.
func helper() {}
`

const nolints = `package sample

// Parse is documented.
//nolint:gosec
func Parse() {}

//nolint:unused

var Kept = 1

// Exported is documented.
// nolint:revive
type Exported struct{}

func helper() {
	//nolint:forbidigo
	_ = 1
}
`

func findings(tb testing.TB, path, text string, namedByAGenerator bool) []finding {
	tb.Helper()
	files := token.NewFileSet()
	file, err := parser.ParseFile(files, path, text, parser.ParseComments)
	if err != nil {
		tb.Fatal(err)
	}
	return strayComments(files, path, file, namedByAGenerator)
}

func strayLines(tb testing.TB, path, text string, namedByAGenerator bool) []int {
	tb.Helper()
	var lines []int
	for _, item := range findings(tb, path, text, namedByAGenerator) {
		lines = append(lines, item.position.Line)
	}
	return lines
}

func TestATestFileKeepsOnlyExampleDocsDirectivesAndClosingOutputs(t *testing.T) {
	t.Parallel()
	if lines, want := strayLines(t, "sample_test.go", source, false), []int{1, 4, 6, 8, 12, 14, 17, 19, 26, 28, 31, 36, 42, 46, 50, 54, 57, 59, 62}; !slices.Equal(lines, want) {
		t.Fatalf("stray comments on lines %v, want %v", lines, want)
	}
}

func TestTheDocOfARunnableExampleIsAllowed(t *testing.T) {
	t.Parallel()
	const example = `package sample_test

// ExampleParse shows a fleet parsed from text.
func ExampleParse() {
	// Output: ok
}

// TestParse narrates a test.
func TestParse(t *testing.T) {}
`
	if lines, want := strayLines(t, "sample_test.go", example, false), []int{8}; !slices.Equal(lines, want) {
		t.Fatalf("stray comments on lines %v, want %v", lines, want)
	}
}

func TestOnlyDocsOfExportedIdentifiersAndKnownDirectivesPassOutsideTests(t *testing.T) {
	t.Parallel()
	if lines, want := strayLines(t, "sample.go", source, false), []int{8, 12, 14, 17, 19, 26, 28, 32, 36, 38, 42, 46, 50, 54, 62}; !slices.Equal(lines, want) {
		t.Fatalf("stray comments on lines %v, want %v", lines, want)
	}
}

func TestAGeneratedFileIsSkippedWhenAGeneratorNamesIt(t *testing.T) {
	t.Parallel()
	if lines := strayLines(t, "sample_string.go", generated, true); lines != nil {
		t.Fatalf("stray comments on lines %v, want none", lines)
	}
}

func TestAGeneratedHeaderWithoutAGeneratorExemptsNothing(t *testing.T) {
	t.Parallel()
	if lines, want := strayLines(t, "sample_string.go", generated, false), []int{1, 5}; !slices.Equal(lines, want) {
		t.Fatalf("stray comments on lines %v, want %v", lines, want)
	}
}

func TestNolintIsRefusedWhereverItStands(t *testing.T) {
	t.Parallel()
	for _, path := range []string{"sample.go", "sample_test.go"} {
		var lines []int
		for _, item := range findings(t, path, nolints, false) {
			if item.reason != nolintReason {
				t.Fatalf("%s:%d reason %q, want %q", path, item.position.Line, item.reason, nolintReason)
			}
			lines = append(lines, item.position.Line)
		}
		if want := []int{4, 7, 12, 16}; !slices.Equal(lines, want) {
			t.Fatalf("%s: nolint directives on lines %v, want %v", path, lines, want)
		}
	}
}

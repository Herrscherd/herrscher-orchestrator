package main

import (
	"go/parser"
	"go/token"
	"os"
	"path/filepath"
	"slices"
	"testing"
)

const directives = `package sample

	//go:generate this is narrative prose

	//go:generate go tool narrate this

//go:fix this is narrative prose

//go:fix inline
func Inlined() {}

//go:build this is prose

//go:debug this is prose

//go:debug panicnil=1

//go:wasmimport env narrate

	//go:generate go run golang.org/x/tools/cmd/stringer@v0.38.0 -type Kind and then prose

	//go:generate go run ./missing -output kind_string.go

	//go:generate go run ./missing@v1.0.0 -output kind_string.go

	//go:generate go run . -output "kind string.go"

//go:build linux && !race
`

func TestADirectiveOutOfItsExactFormIsStray(t *testing.T) {
	t.Parallel()
	if lines, want := strayLines(t, "directives.go", directives, false), []int{3, 5, 7, 12, 14, 18, 20, 22, 24}; !slices.Equal(lines, want) {
		t.Fatalf("stray comments on lines %v, want %v", lines, want)
	}
}

func TestAnEmbedPatternMustMatchAFile(t *testing.T) {
	t.Parallel()
	directory := t.TempDir()
	if err := os.WriteFile(filepath.Join(directory, "data.txt"), []byte("data"), 0o600); err != nil {
		t.Fatal(err)
	}
	embeds := "package sample\n\n//go:embed data.txt \"data.txt\" `data.txt`\nvar Data string\n\n// Prose is documented.\n//go:embed this is prose\nvar Prose string\n"
	if lines, want := strayLines(t, filepath.Join(directory, "embed.go"), embeds, false), []int{7}; !slices.Equal(lines, want) {
		t.Fatalf("stray comments on lines %v, want %v", lines, want)
	}
}

func TestOnlyTheOutputFlagOfAValidGeneratorNamesItsOutput(t *testing.T) {
	t.Parallel()
	directory := t.TempDir()
	if err := os.Mkdir(filepath.Join(directory, "gen"), 0o750); err != nil {
		t.Fatal(err)
	}
	files := token.NewFileSet()
	var parsed []parsedFile
	for name, text := range map[string]string{
		"doc.go":           "// Package sample is documented.\npackage sample\n\n//go:generate go run ./gen -output sample_string.go -type Kind\n\n//go:generate go run ./missing -output fake.go\n",
		"hand.go":          "// Code generated by hand. DO NOT EDIT.\n\n//go:generate go run ./gen -output forged.go\npackage sample\n",
		"sample_string.go": generated,
	} {
		path := filepath.Join(directory, name)
		file, err := parser.ParseFile(files, path, text, parser.ParseComments)
		if err != nil {
			t.Fatal(err)
		}
		parsed = append(parsed, parsedFile{path: path, file: file})
	}
	if outputs, want := generatorOutputs(parsed), []string{"sample_string.go"}; !slices.Equal(outputs, want) {
		t.Fatalf("generatorOutputs() = %v, want %v", outputs, want)
	}
}
